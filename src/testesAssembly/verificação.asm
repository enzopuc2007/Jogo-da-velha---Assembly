TITLE VERIFICAO_VIT
.MODEL SMALL
.STACK 100h
.DATA
MATRIZ DB 6Fh,6Fh,6Fh
       DB 78h,6Fh,78h
       DB 78h,78h,78h

.CODE
 MAIN PROC
    XOR BX,BX
    XOR DX,DX
    MOV CX,3
AGAIN1:
    CMP MATRIZ[BX],6Fh
    JNE CONT1
    INC DH
    JMP SAI1
CONT1:
    CMP MATRIZ[BX],78h
    JNE SAI1
    INC DL
SAI1:
    INC BX
    LOOP AGAIN1

    XOR DX,DX 
    MOV CX,3
AGAIN2:
    CMP MATRIZ[BX],6Fh
    JNE CONT2
    INC DH
    JMP SAI2
CONT2:
    CMP MATRIZ[BX],78h
    JNE SAI2
    INC DL
SAI2:
    INC BX
    LOOP AGAIN2

    XOR DX,DX
    MOV CX,3
AGAIN3:
    CMP MATRIZ[BX],6Fh
    JNE CONT3
    INC DH
    JMP SAI3
 MAIN ENDP
END MAIN